export interface IndianState {
  readonly id: string;
  readonly name: string;
  readonly districts: readonly string[];
}

export const INDIAN_STATES: readonly IndianState[] = ROWS.map(
  ([id, name, districts]) => ({ id, name, districts }),
);

const BY_ID = new Map(INDIAN_STATES.map((state) => [state.id, state]));

export function stateById(id: string): IndianState | undefined {
  return BY_ID.get(id);
}

/** The districts of one state, or nothing for an id that is not a state. */
export function districtsOf(stateId: string): readonly string[] {
  return BY_ID.get(stateId)?.districts ?? [];
}

/**
 * Whether a district belongs to the state it was submitted with.
 *
 * Checked on the server as well as in the form: the pair arrives from a
 * browser, and "Erode, Punjab" would otherwise be stored and then shown to
 * operations as though somebody had meant it.
 */
export function isDistrictOf(stateId: string, district: string): boolean {
  const wanted = district.trim().toLowerCase();
  return districtsOf(stateId).some((name) => name.toLowerCase() === wanted);
}

