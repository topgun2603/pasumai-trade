/**
 * Every state, union territory and district in India, for address entry.
 *
 * ## Why this is separate from `lib/mock/locations.ts`
 *
 * That module is the geography the platform *operates* in: districts with a
 * minimum order value, villages with coordinates, an `active` flag that decides
 * what dispatch and the coverage map will admit to. It is small on purpose,
 * and the counts on the public site are computed from it.
 *
 * This module is the administrative map of the country, and it exists for one
 * job: letting somebody in Sangli or Sonipat write down where they are when
 * they register. Merging the two would make "districts covered" mean 727, which
 * would be a claim rather than a count.
 *
 * So: address fields read from here, coverage and dispatch read from there, and
 * an account may name a district the platform has nobody in — which is a thing
 * operations needs to see, not a thing to prevent.
 *
 * ## Accuracy
 *
 * A snapshot, and districts are created often — several states have split
 * districts since this was compiled. It was cleaned against the position after
 * the 2019 and 2020 reorganisations: Ladakh separated from Jammu and Kashmir,
 * Dadra and Nagar Haveli merged with Daman and Diu, and Andaman and Nicobar
 * Islands added, none of which the source carried.
 *
 * When it goes stale, operations adds the district in Controls rather than
 * waiting for a deploy — the same escape hatch every other reference list here
 * has.
 *
 * Names are the current ones, with the source's parentheticals resolved:
 * "Mysuru (Mysore)" is stored as Mysuru. Where the bracket was the only thing
 * telling two districts apart it became a suffix instead — Telangana has
 * Warangal Rural and Warangal Urban, not two districts called Warangal.
 */

